/**
 * Precomputes the land dots drawn on the hero globe, so the browser needs no
 * map library. Run after changing the density:
 *
 *   npm run generate:globe
 *
 * Writes components/site/globe-dots.ts (base64 Int16 pairs: lat*100, lng*100).
 * Land outlines: Natural Earth via world-atlas (public domain).
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { geoContains } from "d3-geo";
import { feature } from "topojson-client";
import type { GeometryCollection, Topology } from "topojson-specification";

const SPACING_DEG = 1.9;

const topology = JSON.parse(
  readFileSync(join(process.cwd(), "node_modules/world-atlas/land-50m.json"), "utf8"),
) as Topology<{ land: GeometryCollection }>;
const land = feature(topology, topology.objects.land);

const values: number[] = [];
let row = 0;
for (let lat = -56; lat <= 78; lat += SPACING_DEG, row++) {
  // Keep spacing even on the sphere: wider longitude steps towards the poles.
  const step = SPACING_DEG / Math.max(0.2, Math.cos((lat * Math.PI) / 180));
  const offset = row % 2 ? step / 2 : 0; // staggered rows look less like a grid
  for (let lng = -180 + offset; lng < 180; lng += step) {
    if (geoContains(land, [lng, lat])) values.push(Math.round(lat * 100), Math.round(lng * 100));
  }
}

const base64 = Buffer.from(new Int16Array(values).buffer).toString("base64");
const out = `// Generated by scripts/generate-globe-dots.ts. Do not edit.
// ${values.length / 2} land dots, spacing ${SPACING_DEG}°. Base64 Int16 pairs (lat*100, lng*100).
export const GLOBE_DOTS = "${base64}";
`;
writeFileSync(join(process.cwd(), "components/site/globe-dots.ts"), out);
console.log(`Wrote ${values.length / 2} dots (${Math.round(base64.length / 1024)} KB)`);
